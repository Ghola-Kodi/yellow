#!/usr/bin/env node
/**
 * apply-supabase.mjs — apply the dunning schema migrations (0001–0008 + 0099)
 * to your Supabase project, replacing the old flat schema.
 *
 * Two modes:
 *
 *  1. Automated (recommended) — provide a Supabase Personal Access Token:
 *       set SUPABASE_ACCESS_TOKEN=sbp_xxxx  (in .env.local or the environment)
 *       node scripts/apply-supabase.mjs
 *     Each migration is POSTed to the Management API "Run SQL" endpoint.
 *
 *  2. Manual — with no token, writes supabase/apply_schema.sql (everything
 *     concatenated, in order). Open Supabase → SQL Editor → paste → Run.
 *
 * Token scope: create it at https://supabase.com/dashboard/account/tokens and
 * enable WRITE access to the project (the SQL editor / database scope).
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..');

// ---- load .env.local without clobbering real env ---------------------------
function loadEnv(name) {
  const path = resolve(projectRoot, name);
  if (!existsSync(path)) return;
  for (const raw of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}
loadEnv('.env.local');
loadEnv('.env');

const url = (process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL || '').replace(/\/+$/, '');
const token = process.env.SUPABASE_ACCESS_TOKEN || process.env.SUPABASE_PAT || '';

if (!url) {
  console.error('❌ Missing SUPABASE_URL / NEXT_PUBLIC_SUPABASE_URL');
  process.exit(1);
}

// Project ref = the host prefix, e.g. https://wkifwiiagbbjargrrsiw.supabase.co
const ref = url.replace(/^https?:\/\//, '').replace(/\.supabase\.co.*$/, '');

const FILES = [
  '0001_webhook_receipts.sql',
  '0002_customers_subscriptions.sql',
  '0003_dunning_cycles_attempts.sql',
  '0004_klaviyo_sends.sql',
  '0005_dead_letter_events.sql',
  '0006_simulator_attempts.sql',
  '0007_reporting_views.sql',
  '0008_seed_demo.sql',
  '0099_legacy_cleanup.sql',
];

const sqlBlocks = FILES.map((f) => {
  const p = join(projectRoot, 'supabase', 'migrations', f);
  if (!existsSync(p)) throw new Error(`Missing migration file: ${f}`);
  return { file: f, sql: readFileSync(p, 'utf8') };
});

// ---- Manual mode: emit a single paste-ready file ---------------------------
if (!token) {
  const header = [
    '-- =============================================================================',
    '-- Generated by scripts/apply-supabase.mjs — paste into Supabase SQL Editor.',
    '-- Project: ' + url,
    '-- Applies the normalized dunning schema (0001–0008) and drops the old flat',
    '-- schema (0099). All statements are idempotent, so this is safe to re-run.',
    '-- =============================================================================',
  ].join('\n');

  const combined = [header, ...sqlBlocks.map(({ file, sql }) => `-- ---- ${file} ----\n${sql}`)].join('\n\n');

  const out = join(projectRoot, 'supabase', 'apply_schema.sql');
  writeFileSync(out, combined + '\n');
  console.log(`✅ Wrote ${out} (${combined.length.toLocaleString()} bytes)`);
  console.log('');
  console.log('Next: Supabase → SQL Editor → New query → paste the whole file → Run.');
  console.log('   (or set SUPABASE_ACCESS_TOKEN and re-run to apply automatically)');
  process.exit(0);
}

// ---- Automated mode: Management API ---------------------------------------
console.log(`Applying migrations to project ${ref} via Management API...\n`);

let failed = 0;
for (const { file, sql } of sqlBlocks) {
  let res;
  try {
    res = await fetch(`https://api.supabase.com/v1/projects/${ref}/database/query`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ query: sql }),
    });
  } catch (error) {
    console.error(`❌ ${file} — network error: ${error instanceof Error ? error.message : error}`);
    failed++;
    continue;
  }

  const text = await res.text();
  if (res.ok) {
    console.log(`✅ ${file} — ok (${res.status})`);
  } else {
    let detail = text;
    try { detail = JSON.parse(text).message || JSON.parse(text).msg || text; } catch { /* keep raw */ }
    console.error(`❌ ${file} — ${res.status}: ${detail}`);
    failed++;
  }
}

console.log('');
if (failed === 0) {
  console.log('🎉 All migrations applied. The old flat schema is gone; the dunning engine is live.');
} else {
  console.error(`${failed} migration(s) failed — review the output above. The script is idempotent, so fix and re-run.`);
  process.exit(1);
}
